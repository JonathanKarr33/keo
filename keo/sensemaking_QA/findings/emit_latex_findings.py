#!/usr/bin/env python3
"""
Emit a LaTeX snippet for appendix from cool_findings.json (oracle router + rarity).
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
FINDINGS = ROOT / "out" / "cool_findings.json"
OUT_TEX = ROOT / "out" / "findings_snip.tex"


def main():
    if not FINDINGS.exists():
        raise SystemExit(f"Run mine_cool_findings.py first ({FINDINGS} missing)")
    data = json.loads(FINDINGS.read_text())
    oracle = data["oracle_router_from_paper_tables"]
    rarity = data["rarity_demo"]

    lines = [
        "% Auto-generated by findings/emit_latex_findings.py — do not hand-edit",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Oracle task-routing upper bound using published overall scores "
        r"(sensemaking $n{=}83$, action $n{=}50$; GPT-4o judge). "
        r"Routed = KEO on sensemaking + text-chunk on action.}",
        r"\label{tab:oracle_router}",
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"\textbf{Model} & \textbf{Always KEO} & \textbf{Always chunk} & \textbf{Oracle routed} & \textbf{$\Delta$ vs KEO} \\",
        r"\midrule",
    ]
    for model, o in oracle.items():
        nice = model.replace("-it", "")
        sign = "+" if o["gain_vs_always_keo"] >= 0 else ""
        lines.append(
            f"{nice} & {o['always_keo']:.2f} & {o['always_textchunk']:.2f} & "
            f"{o['oracle_routed']:.2f} & {sign}{o['gain_vs_always_keo']:.2f} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
        r"\paragraph{Rarity finding.}",
        (
            f"On the human-structure KG ({rarity.get('n_edges', '?')} edges), "
            f"{rarity.get('n_severity_critical', '?')} edges match a high-severity lexicon and "
            f"{rarity.get('n_severity_safety', '?')} are safety-relevant; "
            f"{rarity.get('critical_buried_in_bottom_80pct_freq', '?')} high-severity and "
            f"{rarity.get('safety_buried_in_bottom_80pct_freq', '?')} safety-relevant edges fall outside the top "
            r"20\% by frequency---motivating rarity/severity weighting for safety-critical retrieval."
        ),
    ]
    OUT_TEX.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT_TEX}")


if __name__ == "__main__":
    main()
