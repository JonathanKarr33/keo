"""Decide whether a judged arm can be skipped, or must be scored again.

Arm directories are named by ablation, not by answerer. Generating with a new model
overwrites `answers.json` / `answers_meta.json` in place; the old evaluation JSON is
left sitting next to them. Skipping on "an eval file exists" then attaches the previous
answerer's scores to the new answers. Skip only when the evaluation *records* the same
`answer_model` as `answers_meta.json`.
"""

from __future__ import annotations

import glob
import json
import os
from typing import Optional, Tuple

EVAL_GLOB = "global_sensemaking_evaluation_*.json"
JUDGE_META_SUFFIX = "_judge_meta.json"


def answers_model(meta_path: str) -> Optional[str]:
    if not os.path.isfile(meta_path):
        return None
    try:
        blob = json.load(open(meta_path))
    except (OSError, json.JSONDecodeError):
        return None
    return blob.get("answer_model") or blob.get("answer_model_exact")


def answers_model_from_answers_file(answers_file: str) -> Optional[str]:
    root, _ = os.path.splitext(answers_file)
    return answers_model(root + "_meta.json")


def eval_answer_model(eval_path: str) -> Optional[str]:
    if not os.path.isfile(eval_path):
        return None
    try:
        blob = json.load(open(eval_path))
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(blob, dict):
        return None
    direct = blob.get("answer_model") or blob.get("answer_model_exact")
    if direct:
        return direct
    prov = blob.get("model_provenance") or {}
    if isinstance(prov, dict):
        return prov.get("answer_model") or (prov.get("answer") or {}).get("requested_id")
    return None


def newest_eval(arm_dir: str) -> Optional[str]:
    matches = sorted(glob.glob(os.path.join(arm_dir, EVAL_GLOB)))
    matches = [m for m in matches if not m.endswith(JUDGE_META_SUFFIX)]
    return matches[-1] if matches else None


def should_skip_judge(arm_dir: str, requested_model: Optional[str] = None) -> Tuple[bool, str]:
    """Return (skip, reason). A missing recorded answerer is a refuse, not a skip."""
    eval_path = newest_eval(arm_dir)
    if not eval_path:
        ckpt = os.path.join(arm_dir, "global_sensemaking_checkpoint.json")
        if os.path.isfile(ckpt):
            return False, "checkpoint only (incomplete) — resume judging"
        return False, "no evaluation file"
    try:
        blob = json.load(open(eval_path))
    except (OSError, json.JSONDecodeError):
        return False, f"unreadable evaluation file {os.path.basename(eval_path)}"
    if isinstance(blob, dict) and (blob.get("partial") or blob.get("complete") is False):
        return False, f"{os.path.basename(eval_path)} is marked partial/incomplete"
    # Any method still incomplete → do not skip
    by = blob.get("by_method") if isinstance(blob, dict) else None
    if isinstance(by, dict):
        for name, block in by.items():
            if isinstance(block, dict) and block.get("incomplete"):
                return False, f"{name} incomplete in {os.path.basename(eval_path)}"
    recorded = eval_answer_model(eval_path)
    generated = answers_model(os.path.join(arm_dir, "answers_meta.json"))
    if not recorded:
        return False, (
            f"{os.path.basename(eval_path)} does not record answer_model, so it cannot "
            "be assumed to match the current answers"
        )
    if not generated:
        return False, "answers_meta.json has no answer_model"
    if recorded != generated:
        return False, (
            f"eval was scored for {recorded}, answers were generated by {generated}"
        )
    if requested_model and recorded != requested_model:
        return False, (
            f"eval/answers are {recorded}, this sweep requested {requested_model}"
        )
    return True, os.path.basename(eval_path)


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Print skip/judge for one arm directory")
    parser.add_argument("arm_dir")
    parser.add_argument("--requested-model", default=None)
    args = parser.parse_args()
    skip, reason = should_skip_judge(args.arm_dir, args.requested_model)
    print(("SKIP" if skip else "JUDGE") + f"\t{reason}")
    raise SystemExit(0 if skip else 2)


if __name__ == "__main__":
    main()
